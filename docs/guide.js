function renderGuide() {
  const fmtPhone = (p) => p.replace(/^\+964(\d{3})(\d{3})(\d{4})$/, '+964 $1 $2 $3');
  $('guideBody').innerHTML =
    '<div class="gIntro">مرحبًا بك في <b>الملاح</b> — تطبيق ملاحة عربي يعمل مع الإنترنت وبدونه، ومعه أدوات خاصة للعمل الميداني وقياس المساحات. اضغط على أي قسم لعرض شرحه.</div>'
    + GUIDE.map((g, i) => `<details class="gSec"${i === 0 ? ' open' : ''}><summary><span class="gi">${g.icon}</span>${g.t}</summary><div class="gBody">${g.b}</div></details>`).join('')
    + `<div class="credit">
        <div class="cLogo">🧭</div>
        <div class="cApp">الملاح — الإصدار ${APP_VERSION}</div>
        <div class="cBy">هذا البرنامج من تصميم</div>
        <div class="cName">${DESIGNER.name}</div>
        ${DESIGNER.phones.map((p) => `<div class="cPhone"><span class="ltr">${fmtPhone(p)}</span>
          <button class="chip" data-call="${p}">📞 اتصال</button><button class="chip go" data-wa="${p}">💬 واتساب</button></div>`).join('')}
      </div>`;
  $('guideBody').querySelectorAll('[data-call]').forEach((b) => { b.onclick = () => openExt('tel:' + b.dataset.call); });
  $('guideBody').querySelectorAll('[data-wa]').forEach((b) => { b.onclick = () => openExt('https://wa.me/' + b.dataset.wa.replace(/\D/g, '')); });
  // open one section at a time
  $('guideBody').querySelectorAll('details.gSec').forEach((d) => d.addEventListener('toggle', () => {
    if (d.open) { $('guideBody').querySelectorAll('details.gSec').forEach((o) => { if (o !== d) o.open = false; }); setTimeout(() => d.scrollIntoView({ block: 'start', behavior: 'smooth' }), 50); }
  }));
}
function openExt(url) {
  if (NATIVE && Android.openUrl) { Android.openUrl(url); return; }
  window.open(url, '_blank');
}
function openGuide(section) {
  $('menuDrop').classList.add('hidden');
  renderGuide();
  $('guidePanel').classList.remove('hidden');
  if (section != null) { const d = $('guideBody').querySelectorAll('details.gSec')[section]; if (d) d.open = true; }
}
$('openGuide').onclick = () => openGuide();
